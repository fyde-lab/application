// The fyde server the app connects to, baked in at build time as
// `BuildConfig.SERVER_URL` (generated into commonMain below). `shared` is
// compiled once per target with no build types of its own, so whether this
// is a release build is read off what was asked of Gradle: any requested
// task naming a release/production/distribution build (Android's
// `assembleRelease`/`bundleRelease`, desktop's `package*`/
// `createDistributable`, web's `*Production*`/`*Distribution`), or Xcode's
// `CONFIGURATION=Release` for iOS (`embedAndSignAppleFrameworkForXcode`
// reads the same variable). Everything else — `run`, `assembleDebug`,
// tests, Xcode's Debug configuration — is a dev build. `-Pfyde.serverUrl=…`
// overrides both, e.g. `http://10.0.2.2:40051` to reach a host's dev server
// from the Android emulator.
val devServerUrl = "http://127.0.0.1:40051"
val releaseServerUrl = "https://doc.halium.fr"

val isReleaseBuild: Boolean =
    gradle.startParameter.taskNames.any { requested ->
        val task = requested.substringAfterLast(':')
        !task.contains("debug", ignoreCase = true) &&
            (task.startsWith("package") ||
                listOf("release", "production", "distribution", "distributable")
                    .any { task.contains(it, ignoreCase = true) })
    } || providers.environmentVariable("CONFIGURATION").orNull == "Release"

val serverUrl: String = providers.gradleProperty("fyde.serverUrl").orNull
    ?: if (isReleaseBuild) releaseServerUrl else devServerUrl

val generateBuildConfig by tasks.registering {
    val url = serverUrl
    val outputDir = layout.buildDirectory.dir("generated/buildConfig/commonMain/kotlin")
    inputs.property("serverUrl", url)
    outputs.dir(outputDir)
    doLast {
        val literal = url.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")
        outputDir.get().file("com/peltoche/fyde/BuildConfig.kt").asFile.apply {
            parentFile.mkdirs()
            writeText(
                """
                |// Generated by shared/build.gradle.kts's generateBuildConfig — do not edit.
                |package com.peltoche.fyde
                |
                |internal object BuildConfig {
                |    /** The fyde server this build connects to. */
                |    const val SERVER_URL: String = "$literal"
                |}
                |""".trimMargin()
            )
        }
    }
}

